// --- ОТОБРАЖЕНИЕ КАРТОЧЕК ---
function renderDisorders(disorders) {
    const grid = document.getElementById('disordersGrid');
    grid.innerHTML = '';

    if (disorders.length === 0) {
        grid.innerHTML = '<div class="empty-state"><p>Ничего не найдено 😔</p></div>';
        return;
    }

    disorders.forEach(disorder => {
        const card = document.createElement('div');
        card.className = 'disorder-card';
        card.setAttribute('data-id', disorder.id);

        const symptomsHtml = disorder.symptoms.map(s => `<li>${s}</li>`).join('');
        const tagsHtml = disorder.tags.map(t => `<span>${t}</span>`).join('');

        card.innerHTML = `
            <div class="disorder-header">
                <span class="icon">${disorder.icon}</span>
                <h3>${disorder.name}</h3>
                <span class="arrow">▼</span>
            </div>
            <div class="disorder-body">
                <h4>Симптомы</h4>
                <ul>${symptomsHtml}</ul>
                <h4>Причины</h4>
                <ul>${disorder.causes.map(c => `<li>${c}</li>`).join('')}</ul>
                <h4>Лечение</h4>
                <ul>${disorder.treatment.map(t => `<li>${t}</li>`).join('')}</ul>
                ${tagsHtml ? `<div class="disorder-tags">${tagsHtml}</div>` : ''}
            </div>
        `;

        // Клик по карточке — раскрыть/закрыть
        card.addEventListener('click', function(e) {
            // Если кликнули по ссылке или кнопке внутри — не закрываем
            if (e.target.closest('a') || e.target.closest('button')) return;
            this.classList.toggle('active');
        });

        grid.appendChild(card);
    });
}

// --- ПОИСК ---
function filterDisorders() {
    const query = document.getElementById('searchInput').value.toLowerCase().trim();
    
    if (!query) {
        renderDisorders(disordersData);
        return;
    }

    const filtered = disordersData.filter(d => {
        const nameMatch = d.name.toLowerCase().includes(query);
        const symptomMatch = d.symptoms.some(s => s.toLowerCase().includes(query));
        const tagMatch = d.tags.some(t => t.toLowerCase().includes(query));
        const categoryMatch = d.category.toLowerCase().includes(query);
        return nameMatch || symptomMatch || tagMatch || categoryMatch;
    });

    renderDisorders(filtered);
}

// --- МЕНЮ ДЛЯ МОБИЛЬНЫХ ---
function initMobileMenu() {
    const toggle = document.getElementById('menuToggle');
    const nav = document.querySelector('nav');

    if (toggle && nav) {
        toggle.addEventListener('click', function(e) {
            e.stopPropagation();
            nav.classList.toggle('open');
        });

        // Закрываем при клике вне
        document.addEventListener('click', function(e) {
            if (!nav.contains(e.target) && !toggle.contains(e.target)) {
                nav.classList.remove('open');
            }
        });
    }
}

// --- ЗАПУСК ---
document.addEventListener('DOMContentLoaded', function() {
    renderDisorders(disordersData);

    const searchInput = document.getElementById('searchInput');
    if (searchInput) {
        searchInput.addEventListener('input', filterDisorders);
    }

    initMobileMenu();

    // Закрыть все карточки при переключении поиска
    const observer = new MutationObserver(() => {
        // Просто перерисовываем при изменении поиска
    });
    observer.observe(document.getElementById('disordersGrid'), { childList: true });
});